export type LauncherType = "ballistic" | "parachute" | "flyer" | "ground";

export interface WeaponDef {
  idx: number; // 0=默认炮弹, 1..14=可购买, 15=敌方空投弹
  key: string;
  name: string; // 中文名
  en: string; // 原版英文名
  desc: string; // 商店说明(原版文案中译)
  launcher: LauncherType;
  cost: number; // 购买价$,-1=不可购买(默认/敌方专属)
  upCost: number; // 升级价$(每次),0=不可升级
  upMax: number; // 升级上限
  carryMax: number; // 携带上限
  restockCost: number; // 每发补货价(原版 aReload_cost 未逆向,按购买价 40% 估算)
  reload: number; // 开火冷却(帧)
  v: number; // 出膛初速 px/帧
  gScale: number; // 重力倍率
  power: number[]; // 对敌伤害
  hurt: number[]; // 波及自身/友军伤害
  radius: number[]; // 爆炸半径
  trail?: boolean; // 弹道尾烟
  custom?: string; // 落地行为标签(GroundUnit/特殊弹)
  hidden?: boolean; // 从弹药栏/商店隐藏(保留索引稳定)
}

